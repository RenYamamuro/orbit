/* 表示言語。日本語の文言そのものをキーにして、英語の訳を引く（gettext と同じ考え方）。
   - 訳が無い文言は日本語のまま出す（訳し漏れがあっても画面が壊れない）
   - {n} のような差し込みを使える。英語の訳を [単数, 複数] にすると n で出し分ける
   - 言語は端末ごとの設定。未設定なら端末の言語に合わせる（日本語以外は英語） */
"use strict";

const LANG_KEY = "subman.lang";
const LANG = (() => {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "ja" || v === "en") return v;
  } catch (e) { }
  return /^ja\b/i.test(navigator.language || "") ? "ja" : "en";
})();
document.documentElement.lang = LANG;

function tr(s, p) {
  let r = LANG === "en" && EN[s] != null ? EN[s] : s;
  if (Array.isArray(r)) r = p && p.n === 1 ? r[0] : r[1];
  if (p) r = r.replace(/\{(\w+)\}/g, (m, k) => (p[k] == null ? "" : p[k]));
  return r;
}
// 言語を切り替えて開き直す（固定の文言も含めて入れ替えるため）
function setLang(l) {
  try { localStorage.setItem(LANG_KEY, l); } catch (e) { }
  location.reload();
}

/* ---------- 日付の書き方 ---------- */
const MON_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const MON_EN_LONG = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const DOW_JA = ["日", "月", "火", "水", "木", "金", "土"];
const DOW_EN = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
// m は 1〜12
function monthLabel(m) { return LANG === "en" ? MON_EN[m - 1] : m + "月"; }
function monthLong(m) { return LANG === "en" ? MON_EN_LONG[m - 1] : m + "月"; }
function fmtYM(d) { return LANG === "en" ? MON_EN[d.getMonth()] + " " + d.getFullYear() : d.getFullYear() + "年" + (d.getMonth() + 1) + "月"; }
function fmtMD(d) { return LANG === "en" ? MON_EN[d.getMonth()] + " " + d.getDate() : (d.getMonth() + 1) + "月" + d.getDate() + "日"; }
function fmtYMD(d) {
  return LANG === "en" ? MON_EN[d.getMonth()] + " " + d.getDate() + ", " + d.getFullYear()
    : d.getFullYear() + "年" + (d.getMonth() + 1) + "月" + d.getDate() + "日";
}
function fmtFullDay(d) {
  return LANG === "en" ? DOW_EN[d.getDay()] + ", " + fmtYMD(d) : fmtYMD(d) + "（" + DOW_JA[d.getDay()] + "）";
}

/* ---------- HTML に直接書いてある文言を入れ替える ---------- */
function translateStatic() {
  if (LANG === "ja") return;
  document.title = tr(document.title);
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    const key = n.nodeValue.trim();
    if (!key || EN[key] == null || n.parentElement.closest("script, style")) continue;
    n.nodeValue = n.nodeValue.replace(key, tr(key));
  }
  ["placeholder", "aria-label", "title"].forEach(a =>
    document.querySelectorAll(`[${a}]`).forEach(el => {
      const v = el.getAttribute(a);
      if (EN[v] != null) el.setAttribute(a, tr(v));
    }));
}

